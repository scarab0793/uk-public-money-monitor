"""Raw OCDS release archive for UK procurement sources.

Raw releases are stored exactly as published, one JSON object per line,
in gzip-compressed monthly partitions:

    <root>/<source>/<YYYY-MM>.ndjson.gz

Each line is {"source", "partition_day", "fetched_at", "package": {...},
"release": <unaltered OCDS release>}.  Partitions are keyed by
(ocid, release id); a release that is re-published with different content
replaces the earlier copy and the change is counted in the run report.

On GitHub Actions the partitions are kept as assets of the
``procurement-raw`` GitHub release (outside git history, so the Pages site
stays small).  Locally, and in tests, the same layout lives in a directory.
"""
from __future__ import annotations

import gzip
import hashlib
import json
import os
import subprocess
from pathlib import Path

RAW_RELEASE_TAG = "procurement-raw"


def partition_name(source: str, month: str) -> str:
    return f"{source}--{month}.ndjson.gz"


def parse_partition_name(name: str):
    if not name.endswith(".ndjson.gz") or "--" not in name:
        return None
    source, month = name[: -len(".ndjson.gz")].split("--", 1)
    return source, month


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def read_partition(path: Path):
    if not path.exists():
        return
    with gzip.open(path, "rt", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                yield json.loads(line)


def write_partition(path: Path, rows) -> int:
    """Write rows atomically, sorted for deterministic output."""
    rows = sorted(rows, key=lambda r: (r["release"].get("date") or "", r["release"].get("ocid") or "", r["release"].get("id") or ""))
    tmp = path.with_suffix(".tmp")
    path.parent.mkdir(parents=True, exist_ok=True)
    # mtime=0 keeps the gzip bytes deterministic, so unchanged partitions are not re-uploaded.
    with open(tmp, "wb") as raw:
        with gzip.GzipFile(fileobj=raw, mode="wb", mtime=0, compresslevel=9) as gz:
            for r in rows:
                gz.write((json.dumps(r, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode("utf-8"))
    os.replace(tmp, path)
    return len(rows)


class LocalStore:
    """Directory of partitions; the GitHub store syncs this directory."""

    def __init__(self, root: Path):
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)

    def path(self, source: str, month: str) -> Path:
        return self.root / partition_name(source, month)

    def partitions(self, source: str | None = None):
        out = []
        for p in sorted(self.root.glob("*.ndjson.gz")):
            parsed = parse_partition_name(p.name)
            if parsed and (source is None or parsed[0] == source):
                out.append((parsed[0], parsed[1], p))
        return out

    def publish(self, paths):  # local store: nothing to upload
        return []


class GitHubReleaseStore(LocalStore):
    """Partitions mirrored to assets of a GitHub release via the gh CLI."""

    def __init__(self, root: Path, tag: str = RAW_RELEASE_TAG):
        super().__init__(root)
        self.tag = tag
        self._ensure_release()

    def _gh(self, *args, check=True):
        return subprocess.run(["gh", *args], check=check, capture_output=True, text=True)

    def _ensure_release(self):
        if self._gh("release", "view", self.tag, check=False).returncode != 0:
            self._gh(
                "release", "create", self.tag, "--title", "Raw procurement archive (OCDS)", "--latest=false",
                "--notes",
                "Unaltered OCDS releases from Contracts Finder and Find a Tender, one gzip NDJSON asset per source and month. "
                "Generated by scripts/import_procurement.py. Contains public sector information licensed under the Open Government Licence v3.0.",
            )

    def download_all(self):
        res = self._gh("release", "download", self.tag, "--pattern", "*.ndjson.gz", "--dir", str(self.root), "--clobber", check=False)
        if res.returncode != 0 and "no assets" not in (res.stderr + res.stdout).lower():
            raise RuntimeError("Could not download raw archive: " + res.stderr.strip())

    def publish(self, paths):
        paths = [str(p) for p in paths]
        for i in range(0, len(paths), 20):
            self._gh("release", "upload", self.tag, *paths[i:i + 20], "--clobber")
        return paths


def open_store(root: Path):
    if os.environ.get("PROCUREMENT_RAW_STORE") == "github":
        store = GitHubReleaseStore(root)
        store.download_all()
        return store
    return LocalStore(root)
